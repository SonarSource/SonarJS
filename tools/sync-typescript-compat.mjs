import ts from 'typescript-classic';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
const require = createRequire(import.meta.url);
import fs from 'node:fs';
import crypto from 'node:crypto';
const root = fileURLToPath(new URL('../', import.meta.url));
const provenance = JSON.parse(fs.readFileSync(root + 'packages/typescript/compat/provenance.json'));
const sourcePath = require.resolve('typescript-classic');
const names = JSON.parse(fs.readFileSync(root + 'packages/typescript/supported-exports.json'));
const constants = Object.fromEntries(
  names
    .filter(n => typeof ts[n] === 'object' && n !== 'factory' && n !== 'sys' && n !== 'server')
    .map(n => [n, ts[n]]),
);
const code = fs.readFileSync(sourcePath, 'utf8');
if (
  crypto.createHash('sha256').update(code).digest('hex') !== provenance.sourceSha256 ||
  ts.version !== provenance.version
)
  throw new Error(
    'Reference SDK differs from the pinned syntax adoption; review provenance before syncing',
  );
await emit('constants.json', JSON.stringify(constants, null, 2) + '\n');
const ast = ts.createSourceFile('ts.js', code, 99, true, ts.ScriptKind.JS);
const defs = new Map();
for (const n of ast.statements[1].expression.expression.expression.body.statements) {
  if (ts.isFunctionDeclaration(n) && n.name) defs.set(n.name.text, n);
  if (ts.isVariableStatement(n))
    for (const d of n.declarationList.declarations)
      if (ts.isIdentifier(d.name)) defs.set(d.name.text, d);
}
const helperNames = Object.keys(require('../packages/typescript/compat/helpers.cjs'));
const providerOperations = require('../packages/typescript/compat/provider-operations.json');
const overrides = [...helperNames, ...providerOperations];
const roots = names.filter(n => typeof ts[n] === 'function' && !overrides.includes(n));
const deps = new Set();
function visitDef(name) {
  if (deps.has(name) || overrides.includes(name)) return;
  const def = defs.get(name);
  if (!def) return;
  deps.add(name);
  function walk(n) {
    if (
      ts.isIdentifier(n) &&
      defs.has(n.text) &&
      !(ts.isPropertyAccessExpression(n.parent) && n.parent.name === n) &&
      !(ts.isPropertyAssignment(n.parent) && n.parent.name === n)
    )
      visitDef(n.text);
    ts.forEachChild(n, walk);
  }
  walk(def);
}
for (const name of roots) visitDef(name);
const imports = new Set();
for (const name of deps) {
  function walk(n) {
    if (ts.isIdentifier(n) && overrides.includes(n.text)) imports.add(n.text);
    ts.forEachChild(n, walk);
  }
  walk(defs.get(name));
}
const header = `// Stateless syntax compatibility adopted from Microsoft TypeScript ${provenance.version} (Apache-2.0).
// Generated by tools/sync-typescript-compat.mjs; see NOTICE.md for provenance.
`;
if (
  deps.size > 300 ||
  ['sys', 'createProgram', 'resolveModuleName', 'createSourceFile'].some(name => deps.has(name))
)
  throw new Error('Syntax adoption reached compiler implementation; review the helper boundary');
let output = header + `const { ${[...imports].join(', ')} } = require('./helpers.cjs');\n`;
for (const name of deps) {
  const def = defs.get(name);
  output +=
    (ts.isFunctionDeclaration(def) ? def.getText(ast) : 'const ' + def.getText(ast) + ';') + '\n';
}
output += 'module.exports = { ' + roots.join(', ') + ' };\n';
await emit('syntax.cjs', output);
async function emit(name, contents) {
  const file = root + 'packages/typescript/compat/' + name;
  const formatted = await prettier.format(contents, {
    ...JSON.parse(fs.readFileSync(root + 'package.json')).prettier,
    filepath: file,
  });
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8') !== formatted)
      throw new Error(`Run node tools/sync-typescript-compat.mjs: ${name}`);
  } else fs.writeFileSync(file, formatted);
}

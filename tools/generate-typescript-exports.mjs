import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import ts from 'typescript';

const directory = new URL('../packages/typescript/', import.meta.url);
const names = JSON.parse(await readFile(new URL('supported-exports.json', directory), 'utf8'));
const header =
  (await readFile(new URL('../packages/typescript/index.cjs', import.meta.url), 'utf8')).split(
    '*/',
    1,
  )[0] + '*/\n';
const source =
  header +
  '// Generated by tools/generate-typescript-exports.mjs from supported-exports.json.\n' +
  "import compiler from './index.cjs';\nexport default compiler;\n" +
  names
    .map(
      (name, index) =>
        `const value${index} = compiler.${name};\nexport { value${index} as ${name} };\n`,
    )
    .join('');
async function emit(name, contents) {
  const output = new URL(name, directory);
  if (process.argv.includes('--check')) {
    if ((await readFile(output, 'utf8')) !== contents)
      throw new Error('Run node tools/generate-typescript-exports.mjs');
  } else await writeFile(output, contents);
}
await emit('index.mjs', source);

// Retain compatible reference object types, but expose only supported runtime operations.
const require = createRequire(import.meta.url);
const declaration = require.resolve('typescript-classic/lib/typescript.d.ts');
const program = ts.createProgram([declaration], { noLib: true });
const file = program.getSourceFile(declaration);
const namespace = file.statements.find(
  statement => ts.isModuleDeclaration(statement) && statement.name.text === 'ts',
);
const checker = program.getTypeChecker();
const symbols = checker.getExportsOfModule(checker.getSymbolAtLocation(namespace.name));
const publicNames = new Set(symbols.map(symbol => symbol.name));
const types = symbols
  .filter(symbol => symbol.flags & ts.SymbolFlags.Type && !(symbol.flags & ts.SymbolFlags.Value))
  .map(symbol => symbol.name);
const declared = [...new Set([...types, ...names.filter(name => publicNames.has(name))])].sort();
await emit(
  'index.d.cts',
  header +
    '// Generated by tools/generate-typescript-exports.mjs.\n' +
    "import ts = require('typescript-classic');\n" +
    "import tsserver = require('typescript-classic/lib/tsserverlibrary');\n" +
    'declare namespace compiler {\n' +
    declared.map(name => `  export import ${name} = ts.${name};\n`).join('') +
    '  export import server = tsserver.server;\n}\nexport = compiler;\n',
);

// The facade's npm peer-compatibility version follows the pinned reference provider.
const root = JSON.parse(await readFile(new URL('../../package.json', directory), 'utf8'));
const packageJson = JSON.parse(await readFile(new URL('package.json', directory), 'utf8'));
const referenceVersion = JSON.parse(
  await readFile(require.resolve('typescript-classic/package.json'), 'utf8'),
).version;
if (
  root.dependencies?.['typescript-classic'] &&
  root.dependencies['typescript-classic'] !== `npm:typescript@${referenceVersion}`
) {
  throw new Error('The installed reference compiler does not match package.json');
}
if (packageJson.version !== referenceVersion) {
  if (process.argv.includes('--check')) throw new Error('Regenerate the compiler facade metadata');
  packageJson.version = referenceVersion;
  await writeFile(new URL('package.json', directory), JSON.stringify(packageJson, null, 2) + '\n');
}

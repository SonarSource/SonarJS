import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import ts from 'typescript';
import contract from '../packages/typescript/contract.cjs';
import prettier from 'prettier';
import packageConfiguration from '../package.json' with { type: 'json' };

const directory = new URL('../packages/typescript/', import.meta.url);
const { names, specification } = contract;
const header =
  (await readFile(new URL('../packages/typescript/index.cjs', import.meta.url), 'utf8')).split(
    '*/',
    1,
  )[0] + '*/\n';
const source =
  header +
  '// Generated by tools/generate-typescript-exports.mjs from contract.json.\n' +
  "import compiler from './index.cjs';\nexport default compiler;\n" +
  names
    .map(
      (name, index) =>
        `const value${index} = compiler.${name};\nexport { value${index} as ${name} };\n`,
    )
    .join('');
async function emit(name, contents) {
  const output = new URL(name, directory);
  contents = await prettier.format(contents, {
    ...packageConfiguration.prettier,
    filepath: output.pathname,
  });
  if (process.argv.includes('--check')) {
    if ((await readFile(output, 'utf8')) !== contents)
      throw new Error('Run node tools/generate-typescript-exports.mjs');
  } else await writeFile(output, contents);
}
await emit('index.mjs', source);

// Retain compatible reference object types, but expose only supported runtime operations.
const require = createRequire(import.meta.url);
const declaration = require.resolve('typescript-classic/lib/typescript.d.ts');
const program = ts.createProgram([declaration], { noLib: true });
const file = program.getSourceFile(declaration);
const namespace = file.statements.find(
  statement => ts.isModuleDeclaration(statement) && statement.name.text === 'ts',
);
const checker = program.getTypeChecker();
const symbols = checker.getExportsOfModule(checker.getSymbolAtLocation(namespace.name));
const publicNames = new Set(symbols.map(symbol => symbol.name));
const types = symbols
  .filter(symbol => symbol.flags & ts.SymbolFlags.Type && !(symbol.flags & ts.SymbolFlags.Value))
  .map(symbol => symbol.name);
const privateNames = names.filter(name => !publicNames.has(name));
for (const name of privateNames) {
  if (!specification.internalTypes.compiler[name])
    throw new Error(`Missing private API type: ${name}`);
}
const replaced = new Set([
  'Program',
  'TypeChecker',
  'System',
  'SemanticDiagnosticsBuilderProgram',
  'CreateProgramOptions',
  'createProgram',
  'createSemanticDiagnosticsBuilderProgram',
  'factory',
  'sys',
  'server',
]);
const declared = [...new Set([...types, ...names.filter(name => publicNames.has(name))])]
  .filter(name => !replaced.has(name))
  .sort();
await emit(
  'index.d.cts',
  header +
    '// Generated by tools/generate-typescript-exports.mjs.\n' +
    "import ts = require('typescript-classic');\n" +
    "import tsserver = require('typescript-classic/lib/tsserverlibrary');\n" +
    "import contract = require('./contract.cjs');\n" +
    'declare namespace compiler {\n' +
    declared.map(name => `  export import ${name} = ts.${name};\n`).join('') +
    privateNames
      .map(name => `  export const ${name}: contract.ReferenceCompiler[${JSON.stringify(name)}];\n`)
      .join('') +
    '  export type Program = contract.Program;\n' +
    '  export type TypeChecker = contract.TypeChecker;\n' +
    '  export type System = contract.System;\n' +
    '  export type SemanticDiagnosticsBuilderProgram = contract.BuilderProgram;\n' +
    '  export type CreateProgramOptions = contract.CreateProgramOptions;\n' +
    '  export const createProgram: contract.CreateProgram;\n' +
    '  export const createSemanticDiagnosticsBuilderProgram: contract.CreateBuilderProgram;\n' +
    '  export const factory: contract.Factory;\n' +
    '  export const sys: contract.System;\n' +
    '  export import server = tsserver.server;\n}\nexport = compiler;\n',
);

const keys = names => names.map(name => JSON.stringify(name)).join(' | ');
const members = specification.members;
const checkerSymbol = symbols.find(symbol => symbol.name === 'TypeChecker');
const declaredCheckerMembers = new Set(
  checker
    .getPropertiesOfType(checker.getDeclaredTypeOfSymbol(checkerSymbol))
    .map(symbol => symbol.name),
);
const privateCheckerMembers = members.TypeChecker.filter(name => !declaredCheckerMembers.has(name));
const optionalNames = Object.values(specification.optional).flatMap(feature => feature.exports);
const overrides = ['sys', 'factory', 'createProgram', 'createSemanticDiagnosticsBuilderProgram'];
const required = names.filter(
  name =>
    publicNames.has(name) &&
    !optionalNames.includes(name) &&
    !overrides.includes(name) &&
    !specification.strings.includes(name),
);
const internal = names.filter(name => !publicNames.has(name));
await emit(
  'contract.d.cts',
  header +
    `// Generated from contract.json. Reference declarations supply structural AST compatibility.
import ts = require('typescript-classic');
type ReferenceChecker = ts.TypeChecker${
      privateCheckerMembers.length
        ? ' & { ' +
          privateCheckerMembers
            .map(name => {
              const signature = specification.internalTypes.TypeChecker[name];
              if (!signature) throw new Error(`Missing private checker type: ${name}`);
              return `${name}: ${signature}`;
            })
            .join('; ') +
          ' }'
        : ''
    };
export type TypeChecker = Pick<ReferenceChecker, ${keys(members.TypeChecker)}>;
export type Program = Omit<Pick<ts.Program, ${keys(members.Program)}>, 'getTypeChecker'> & {
  getTypeChecker(): TypeChecker;
};
export type BuilderProgram = Omit<Pick<ts.SemanticDiagnosticsBuilderProgram, ${keys(members.BuilderProgram)}>, 'getProgram'> & {
  getProgram(): Program;
};
export type Factory = Pick<typeof ts.factory, ${keys(members.factory)}>;
export type System = Pick<ts.System, ${keys([...members.sys, ...Object.keys(specification.properties.sys)])}>;
export type CreateProgramOptions = Omit<ts.CreateProgramOptions, 'oldProgram'> & { oldProgram?: Program };
export interface CreateProgram {
  (options: CreateProgramOptions): Program;
  (rootNames: readonly string[], options: ts.CompilerOptions, host?: ts.CompilerHost, oldProgram?: Program, configFileParsingDiagnostics?: readonly ts.Diagnostic[], projectReferences?: readonly ts.ProjectReference[]): Program;
}
export interface CreateBuilderProgram {
  (rootNames: readonly string[] | undefined, options: ts.CompilerOptions | undefined, host?: ts.CompilerHost, oldProgram?: BuilderProgram, configFileParsingDiagnostics?: readonly ts.Diagnostic[], projectReferences?: readonly ts.ProjectReference[]): BuilderProgram;
  (program: Program, host?: ts.BuilderProgramHost, oldProgram?: BuilderProgram, configFileParsingDiagnostics?: readonly ts.Diagnostic[]): BuilderProgram;
}
type InternalBindings = {
${internal.map(name => `  ${name}: ${specification.internalTypes.compiler[name]};`).join('\n')}
};
/** SDK declarations omit these pinned private operations used by the adopted converter. */
export type ReferenceCompiler = typeof ts & InternalBindings;
/** Normalized constant values are checked against constants.json by conformance tests. */
export type Constants = Pick<ReferenceCompiler, ${keys(specification.constants)}>;
/** Adopted helpers preserve reference predicates on normalized nodes. */
export type SyntaxBindings = Pick<ReferenceCompiler, ${keys(specification.syntax)}> & { factory: Factory };
export type CompilerBindings = Pick<typeof ts, ${keys(required)}> & {
  factory: Factory;
  sys: System;
  createProgram: CreateProgram;
  createSemanticDiagnosticsBuilderProgram: CreateBuilderProgram;
} & { [K in ${keys(specification.strings)}]: string } & InternalBindings & Partial<Pick<typeof ts, ${keys(optionalNames.filter(name => publicNames.has(name)))}>>;
export type Capabilities = Readonly<{ ${Object.keys(specification.optional)
      .map(name => `${name}: boolean`)
      .join('; ')} }>;
export interface Provider {
  compiler: CompilerBindings;
  compilerVersion: string;
  /** Retain batch programs only when their backend owns resources requiring explicit release. */
  ownsProgramResources: boolean;
  disposeProgram(program: Program): void;
  close(): void;
  timing?(): unknown;
}
export interface Metadata {
  readonly name: string;
  readonly contractVersion: ${specification.version};
  readonly compilerVersion: string;
  readonly capabilities: Capabilities;
}
export interface ObjectContracts {
  Program: Program;
  BuilderProgram: BuilderProgram;
  TypeChecker: TypeChecker;
  factory: Factory;
  sys: System;
${Object.entries(members)
  .filter(
    ([name]) => !['Program', 'BuilderProgram', 'TypeChecker', 'factory', 'sys'].includes(name),
  )
  .map(
    ([name, properties]) =>
      `  ${name}: Pick<${name === 'sys' ? 'typeof ts.sys' : 'ts.' + name}, ${keys(properties)}>;`,
  )
  .join('\n')}
}
export function defineProvider<T extends Provider>(provider: T): T;
export function assertMembers<T, K extends keyof ObjectContracts>(value: T, category: K): T & ObjectContracts[K];
`,
);
await emit(
  'lifecycle.d.cts',
  header +
    `import type { Metadata, Program } from './contract.cjs';
export const metadata: Metadata;
/** Release a program after its last consumer. Calls are idempotent. */
export function disposeProgram(program: Program): void;
/** Close this worker's compiler session. Existing native programs become invalid. */
export function close(): void;
/** Batch programs are released on success, cancellation and failure. IDE caches retain ownership. */
export function withProgramScope<T>(operation: () => Promise<T>): Promise<T>;
/** Optional backend diagnostics. These are not part of rule semantics. */
export function getTiming(): unknown;
`,
);

// The facade's npm peer-compatibility version follows the pinned reference provider.
const root = JSON.parse(await readFile(new URL('../../package.json', directory), 'utf8'));
const packageJson = JSON.parse(await readFile(new URL('package.json', directory), 'utf8'));
const referenceVersion = JSON.parse(
  await readFile(require.resolve('typescript-classic/package.json'), 'utf8'),
).version;
const referenceDependency =
  root.dependencies?.['typescript-classic'] ?? root.devDependencies?.['typescript-classic'];
if (referenceDependency !== `npm:typescript@${referenceVersion}`) {
  throw new Error('The installed reference compiler does not match package.json');
}
if (packageJson.version !== referenceVersion) {
  if (process.argv.includes('--check')) throw new Error('Regenerate the compiler facade metadata');
  packageJson.version = referenceVersion;
  await writeFile(new URL('package.json', directory), JSON.stringify(packageJson, null, 2) + '\n');
}

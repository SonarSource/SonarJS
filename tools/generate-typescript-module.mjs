import fs from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build, transformSync } from 'esbuild';
import { format, resolveConfig } from 'prettier';
const require = createRequire(import.meta.url);
const ts = require('typescript-classic');
const exports = Object.getOwnPropertyNames(ts)
  .filter(name => /^[A-Za-z_$][\w$]*$/.test(name) && !['default', '__esModule'].includes(name))
  .map((name, i) => `const v${i} = ts[${JSON.stringify(name)}]; export { v${i} as ${name} };`);
const options = await resolveConfig(fileURLToPath(new URL('../package.json', import.meta.url)));
const write = async (file, source) =>
  fs.writeFileSync(
    new URL(file, import.meta.url),
    await format(source, { ...options, parser: 'babel' }),
  );
await write(
  '../packages/typescript/index.mjs',
  '// Generated by tools/generate-typescript-module.mjs. Do not edit.\n' +
    "import ts from './index.cjs';\nexport default ts;\n" +
    exports.join('\n') +
    '\n',
);
await write(
  '../packages/typescript/gateway.cjs',
  '// Generated from gateway.ts by tools/generate-typescript-module.mjs.\n' +
    transformSync(
      fs.readFileSync(new URL('../packages/typescript/gateway.ts', import.meta.url), 'utf8'),
      { loader: 'ts', format: 'cjs', target: 'node24', legalComments: 'inline' },
    ).code,
);
await build({
  entryPoints: [
    fileURLToPath(new URL('../packages/typescript/compat/program.mjs', import.meta.url)),
  ],
  outfile: fileURLToPath(new URL('../packages/typescript/native-compat.mjs', import.meta.url)),
  platform: 'node',
  format: 'esm',
  target: 'node24',
  bundle: true,
  packages: 'external',
  external: ['typescript', 'typescript/*'],
});
